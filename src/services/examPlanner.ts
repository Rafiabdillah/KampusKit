import { Exam, ExamTopic, Note, PlannerSettings, StudyBlock } from '../types';
import { extractPlainText } from '../utils/textExtractor';
import { addDays, formatLocalDate, formatMinutesToTime, parseTimeToMinutes } from '../utils/dateUtils';

export interface ExamPrepPlanDay {
  date: string;
  dayOffset: number; // e.g. -7 means H-7
  isSprintMode: boolean;
  actionTitle: string;
  topics: ExamTopic[];
  targetMinutes: number;
}

/**
 * Builds a structured exam prep schedule spreading topics across available days.
 * If daysAvailable <= 3, switches to Sprint Mode focusing on summary review & flashcards.
 */
export function buildExamPrepPlan(
  exam: Exam,
  daysAvailable: number,
  now: Date = new Date()
): ExamPrepPlanDay[] {
  const topics = exam.topics || [];
  const days = Math.max(1, daysAvailable);
  const isSprintMode = days <= 3;
  const plan: ExamPrepPlanDay[] = [];

  if (isSprintMode) {
    // Sprint Mode: Daily high-yield summary review and active recall
    for (let i = 0; i < days; i++) {
      const planDate = addDays(now, i);
      plan.push({
        date: formatLocalDate(planDate),
        dayOffset: -(days - i),
        isSprintMode: true,
        actionTitle: i === days - 1 
          ? `H-1 Final Sprint: Simulasi Ujian & Active Recall Ringan` 
          : `Sprint Review Intensif: Intisari Topik & Flashcard`,
        topics,
        targetMinutes: 60
      });
    }
    return plan;
  }

  // Standard multi-day distribution (e.g. H-14 to H-1)
  const studyDaysCount = Math.min(days - 1, 14); // Reserve last day for final comprehensive review
  const topicsPerDay = Math.max(1, Math.ceil(topics.length / studyDaysCount));

  for (let i = 0; i < studyDaysCount; i++) {
    const planDate = addDays(now, i);
    const startIndex = i * topicsPerDay;
    const dayTopics = topics.slice(startIndex, startIndex + topicsPerDay);

    if (dayTopics.length > 0) {
      plan.push({
        date: formatLocalDate(planDate),
        dayOffset: -(days - i),
        isSprintMode: false,
        actionTitle: `Kajian Mendalam: ${dayTopics.map(t => t.title).join(', ')}`,
        topics: dayTopics,
        targetMinutes: 45
      });
    }
  }

  // Final review on H-1
  const hMinusOneDate = addDays(now, days - 1);
  plan.push({
    date: formatLocalDate(hMinusOneDate),
    dayOffset: -1,
    isSprintMode: true,
    actionTitle: 'H-1 Review Menyeluruh & Uji Coba Latihan Soal',
    topics,
    targetMinutes: 45
  });

  return plan;
}

/**
 * Extracts exam syllabus topics from course notes offline (as a fast fallback)
 * or online via AI.
 */
export function extractTopicsFromNotesOffline(notes: Note[]): ExamTopic[] {
  const topics: ExamTopic[] = [];
  const seenTitles = new Set<string>();

  for (const n of notes) {
    // 1. Add note title if clean and unique
    if (n.title && n.title.trim()) {
      const cleanTitle = n.title.replace(/^Catatan\s*[:-]?\s*/i, '').trim();
      if (cleanTitle && !seenTitles.has(cleanTitle.toLowerCase())) {
        seenTitles.add(cleanTitle.toLowerCase());
        topics.push({
          id: `topic-${Date.now()}-${Math.random().toString(36).slice(2, 6)}`,
          title: cleanTitle,
          sourceNoteIds: [n.id],
          completed: false,
          masteryLevel: 1
        });
      }
    }

    // 2. Scan for headings (## or ###) inside plain text
    const text = extractPlainText(n.content);
    const headingMatches = text.match(/^#{2,3}\s+(.+)$/gm);
    if (headingMatches) {
      for (const h of headingMatches) {
        const title = h.replace(/^#{2,3}\s+/, '').trim();
        if (title.length >= 4 && title.length <= 60 && !seenTitles.has(title.toLowerCase())) {
          seenTitles.add(title.toLowerCase());
          topics.push({
            id: `topic-${Date.now()}-${Math.random().toString(36).slice(2, 6)}`,
            title,
            sourceNoteIds: [n.id],
            completed: false,
            masteryLevel: 1
          });
        }
      }
    }
  }

  return topics.slice(0, 15); // limit to top 15 relevant syllabus topics
}

export interface ExamBlocksResult {
  blocks: StudyBlock[];
  skippedDates: string[];
}

const LATEST_END_MINUTES = 23 * 60;

/**
 * Mengubah rencana belajar ujian menjadi blok Planner. Blok dibuat sebagai blok
 * pengguna (isAutoGenerated false) supaya "Susun ulang" tidak menimpanya, dan
 * digeser setelah blok lain di hari yang sama. Hari tanpa ruang dicatat di skippedDates.
 */
export function examPlanToStudyBlocks(
  exam: Exam,
  plan: ExamPrepPlanDay[],
  existingBlocks: StudyBlock[],
  settings: Pick<PlannerSettings, 'preferredStudyHours' | 'breakIntervalMinutes'>,
  now: number = Date.now()
): ExamBlocksResult {
  const blocks: StudyBlock[] = [];
  const skippedDates: string[] = [];
  const prefStart = parseTimeToMinutes(settings.preferredStudyHours?.start || '18:00');
  const gap = settings.breakIntervalMinutes || 10;

  for (const day of plan) {
    const busy = existingBlocks
      .filter(b => b.date === day.date)
      .map(b => ({ start: parseTimeToMinutes(b.startTime), end: parseTimeToMinutes(b.endTime) }))
      .sort((a, b) => a.start - b.start);

    let start = prefStart;
    for (const slot of busy) {
      if (start < slot.end + gap && start + day.targetMinutes + gap > slot.start) {
        start = Math.max(start, slot.end + gap);
      }
    }
    const end = start + day.targetMinutes;
    if (end > LATEST_END_MINUTES) {
      skippedDates.push(day.date);
      continue;
    }

    blocks.push({
      id: `exam-${exam.id}-${day.date}`,
      title: `${exam.title}: ${day.actionTitle}`.slice(0, 90),
      date: day.date,
      startTime: formatMinutesToTime(start),
      endTime: formatMinutesToTime(end),
      type: 'EXAM_PREP',
      courseId: exam.courseId,
      examId: exam.id,
      completed: false,
      isAutoGenerated: false,
      updatedAt: now
    });
  }

  return { blocks, skippedDates };
}
