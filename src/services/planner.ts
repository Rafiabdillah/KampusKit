import { Course, Task, CalendarEvent, Exam, StudyBlock, PlannerSettings, TaskStatus, Priority } from '../types';
import { 
  formatLocalDate, 
  parseDeadline, 
  parseTimeToMinutes, 
  formatMinutesToTime, 
  diffDays,
  addDays 
} from '../utils/dateUtils';

export interface GeneratePlanParams {
  now: Date;
  courses: Course[];
  tasks: Task[];
  calendarEvents?: CalendarEvent[];
  exams?: Exam[];
  existingBlocks: StudyBlock[];
  settings: PlannerSettings;
  dueFlashcardsCount?: number;
  daysToPlan?: number; // default 7 days
}

interface TimeInterval {
  start: number; // minutes from 00:00
  end: number;
}

const INDONESIAN_DAYS = ['Minggu', 'Senin', 'Selasa', 'Rabu', 'Kamis', 'Jumat', 'Sabtu'];

/**
 * Finds non-overlapping busy intervals for a given date
 */
function getBusyIntervals(
  date: Date,
  courses: Course[],
  calendarEvents: CalendarEvent[],
  manualBlocks: StudyBlock[]
): TimeInterval[] {
  const intervals: TimeInterval[] = [];
  const dateStr = formatLocalDate(date);
  const dayName = INDONESIAN_DAYS[date.getDay()];

  // 1. Regular weekly courses for this day
  for (const c of courses) {
    if (c.day?.trim().toLowerCase() === dayName.toLowerCase()) {
      const start = parseTimeToMinutes(c.startTime);
      const end = parseTimeToMinutes(c.endTime);
      if (start < end) {
        intervals.push({ start, end });
      }
    }
  }

  // 2. Academic Calendar Events on this date
  for (const ev of calendarEvents) {
    if (ev.type === 'ACADEMIC') {
      if (ev.date === dateStr) {
        if (ev.time) {
          // CalendarEvent tidak punya jam selesai: anggap 60 menit.
          const start = parseTimeToMinutes(ev.time);
          intervals.push({ start, end: Math.min(24 * 60, start + 60) });
        } else {
          // Acara seharian: blok 09:00-11:00 sebagai default aman.
          intervals.push({ start: 9 * 60, end: 11 * 60 });
        }
      }
    }
  }

  // 3. User-created manual blocks for this date
  for (const mb of manualBlocks) {
    if (mb.date === dateStr) {
      const start = parseTimeToMinutes(mb.startTime);
      const end = parseTimeToMinutes(mb.endTime);
      if (start < end) {
        intervals.push({ start, end });
      }
    }
  }

  // Merge overlapping busy intervals
  if (intervals.length === 0) return [];
  intervals.sort((a, b) => a.start - b.start);

  const merged: TimeInterval[] = [intervals[0]];
  for (let i = 1; i < intervals.length; i++) {
    const prev = merged[merged.length - 1];
    const curr = intervals[i];
    if (curr.start <= prev.end) {
      prev.end = Math.max(prev.end, curr.end);
    } else {
      merged.push(curr);
    }
  }

  return merged;
}

/**
 * Finds available study windows within preferred study hours, avoiding busy intervals
 */
function getFreeSlots(
  preferredStart: number,
  preferredEnd: number,
  busy: TimeInterval[]
): TimeInterval[] {
  const free: TimeInterval[] = [];
  let currentStart = preferredStart;

  for (const b of busy) {
    if (b.end <= currentStart) continue;
    if (b.start >= preferredEnd) break;

    if (b.start > currentStart) {
      const slotEnd = Math.min(b.start, preferredEnd);
      if (slotEnd - currentStart >= 15) {
        free.push({ start: currentStart, end: slotEnd });
      }
    }
    currentStart = Math.max(currentStart, b.end);
  }

  if (currentStart < preferredEnd && preferredEnd - currentStart >= 15) {
    free.push({ start: currentStart, end: preferredEnd });
  }

  return free;
}

export function generatePlan({
  now,
  courses,
  tasks,
  calendarEvents = [],
  exams = [],
  existingBlocks = [],
  settings,
  dueFlashcardsCount = 0,
  daysToPlan = 7
}: GeneratePlanParams): StudyBlock[] {
  // Preserve all manual blocks
  const manualBlocks = existingBlocks.filter(b => !b.isAutoGenerated);
  const generatedBlocks: StudyBlock[] = [];

  const prefStart = parseTimeToMinutes(settings.preferredStudyHours?.start || '18:00');
  const prefEnd = parseTimeToMinutes(settings.preferredStudyHours?.end || '22:00');
  const targetMinutesPerDay = settings.dailyStudyTargetMinutes || 120;
  const breakMinutes = settings.breakIntervalMinutes || 10;

  // Filter pending tasks
  const pendingTasks = tasks.filter(t => t.status !== TaskStatus.DONE);

  for (let dayOffset = 0; dayOffset < daysToPlan; dayOffset++) {
    const targetDate = addDays(now, dayOffset);
    const dateStr = formatLocalDate(targetDate);

    // Calculate busy intervals
    const busy = getBusyIntervals(targetDate, courses, calendarEvents, manualBlocks);

    // Free slots in preferred study window
    let freeSlots = getFreeSlots(prefStart, prefEnd, busy);

    // If preferred window is completely booked, expand search into afternoon (14:00-18:00) or morning (07:00-11:00)
    if (freeSlots.length === 0) {
      freeSlots = getFreeSlots(14 * 60, 18 * 60, busy);
      if (freeSlots.length === 0) {
        freeSlots = getFreeSlots(7 * 60, 11 * 60, busy);
      }
    }

    if (freeSlots.length === 0) continue;

    // Existing manual minutes on this date
    const manualMinutes = manualBlocks
      .filter(b => b.date === dateStr)
      .reduce((sum, b) => sum + (parseTimeToMinutes(b.endTime) - parseTimeToMinutes(b.startTime)), 0);

    let allocatedMinutes = manualMinutes;
    const remainingTargetMinutes = Math.max(0, targetMinutesPerDay - allocatedMinutes);
    if (remainingTargetMinutes <= 0) continue;

    // Queue of candidates to allocate for this date
    interface PlanCandidate {
      title: string;
      courseId?: string;
      taskId?: string;
      type: 'TASK' | 'EXAM_PREP' | 'REVIEW_FLASHCARDS';
      priorityScore: number;
      duration: number; // in minutes
    }

    const candidates: PlanCandidate[] = [];

    // Priority 1: Flashcards due on today (offset 0)
    if (dayOffset === 0 && dueFlashcardsCount > 0) {
      candidates.push({
        title: `Spaced Repetition: ${dueFlashcardsCount} Kartu Hafalan`,
        type: 'REVIEW_FLASHCARDS',
        priorityScore: 90,
        duration: Math.min(25, remainingTargetMinutes)
      });
    }

    // Priority 2: Approaching Exams (H-7 to H-1)
    for (const ex of exams) {
      const daysUntil = diffDays(dateStr, ex.date);
      if (daysUntil >= 0 && daysUntil <= 7) {
        candidates.push({
          title: `Persiapan ${ex.kind || 'Ujian'}: ${ex.title || 'Mata Kuliah'}`,
          courseId: ex.courseId,
          type: 'EXAM_PREP',
          priorityScore: 100 - daysUntil * 5, // closer exam has higher priority
          duration: 45
        });
      }
    }

    // Priority 3: Tasks due soon
    for (const t of pendingTasks) {
      const daysUntil = diffDays(dateStr, t.deadline);
      // Allocate if deadline is within next 5 days
      if (daysUntil >= 0 && daysUntil <= 5) {
        let score = 50 - daysUntil * 8;
        if (t.priority === Priority.HIGH) score += 40;
        if (t.priority === Priority.MEDIUM) score += 15;

        const duration = Math.min(60, Math.max(30, t.estimatedMinutes || 45));
        candidates.push({
          title: t.title,
          courseId: t.courseId,
          taskId: t.id,
          type: 'TASK',
          priorityScore: score,
          duration
        });
      }
    }

    // Sort candidates by priority score descending
    candidates.sort((a, b) => b.priorityScore - a.priorityScore);

    // Allocate candidates into free slots
    let currentSlotIdx = 0;
    let currentSlotTime = freeSlots[0].start;

    for (const item of candidates) {
      if (allocatedMinutes >= targetMinutesPerDay) break;
      if (currentSlotIdx >= freeSlots.length) break;

      const currentSlot = freeSlots[currentSlotIdx];
      const slotRemaining = currentSlot.end - currentSlotTime;

      // Fit item into current slot
      const durationToAllocate = Math.min(
        item.duration,
        slotRemaining,
        targetMinutesPerDay - allocatedMinutes
      );

      if (durationToAllocate >= 15) {
        const blockStart = currentSlotTime;
        const blockEnd = currentSlotTime + durationToAllocate;

        generatedBlocks.push({
          id: `block-${dateStr}-${blockStart}-${Math.random().toString(36).slice(2, 6)}`,
          title: item.title,
          courseId: item.courseId,
          taskId: item.taskId,
          date: dateStr,
          startTime: formatMinutesToTime(blockStart),
          endTime: formatMinutesToTime(blockEnd),
          type: item.type,
          completed: false,
          isAutoGenerated: true,
          updatedAt: Date.now()
        });

        allocatedMinutes += durationToAllocate;
        currentSlotTime = blockEnd + breakMinutes; // insert break interval

        if (currentSlotTime >= currentSlot.end) {
          currentSlotIdx++;
          if (currentSlotIdx < freeSlots.length) {
            currentSlotTime = freeSlots[currentSlotIdx].start;
          }
        }
      } else {
        // Move to next slot if current slot has less than 15 mins
        currentSlotIdx++;
        if (currentSlotIdx < freeSlots.length) {
          currentSlotTime = freeSlots[currentSlotIdx].start;
        }
      }
    }
  }

  // Combine manual and generated blocks sorted by date and time
  const combined = [...manualBlocks, ...generatedBlocks];
  combined.sort((a, b) => {
    if (a.date !== b.date) return a.date.localeCompare(b.date);
    return a.startTime.localeCompare(b.startTime);
  });

  return combined;
}
