import { describe, it, expect } from 'vitest';
import { generatePlan } from '../src/services/planner';
import { Course, Task, StudyBlock, PlannerSettings, Priority, TaskStatus } from '../src/types';
import { parseTimeToMinutes } from '../src/utils/dateUtils';

describe('planner service', () => {
  const defaultSettings: PlannerSettings = {
    dailyStudyTargetMinutes: 120,
    preferredStudyHours: { start: '18:00', end: '22:00' },
    breakIntervalMinutes: 10,
    updatedAt: Date.now()
  };

  // Fixed test reference date: Monday 2026-11-02 at 08:00 AM local
  const mockNow = new Date(2026, 10, 2, 8, 0, 0); // Month 10 is November in JS 0-indexed

  it('does not overwrite or collide with scheduled course hours', () => {
    // Class from 18:00 to 20:00 on Monday ('Senin')
    const courses: Course[] = [
      { id: 'c1', name: 'Algoritma', room: 'Lab 1', day: 'Senin', startTime: '18:00', endTime: '20:00', lecturer: 'Dr. A', credits: 3 }
    ];
    const tasks: Task[] = [
      { id: 't1', title: 'Tugas 1', subject: 'Algoritma', deadline: '2026-11-03', status: TaskStatus.TODO, priority: Priority.HIGH, tags: [], subtasks: [], createdAt: 1 }
    ];

    const plan = generatePlan({
      now: mockNow,
      courses,
      tasks,
      existingBlocks: [],
      settings: defaultSettings,
      daysToPlan: 1
    });

    // Check that no block is scheduled between 18:00 and 20:00 on Monday 2026-11-02
    for (const b of plan) {
      if (b.date === '2026-11-02') {
        const start = parseTimeToMinutes(b.startTime);
        const end = parseTimeToMinutes(b.endTime);
        const classStart = 18 * 60;
        const classEnd = 20 * 60;

        const overlaps = start < classEnd && end > classStart;
        expect(overlaps).toBe(false);
      }
    }
  });

  it('prioritizes urgent task with nearer deadline and HIGH priority', () => {
    const tasks: Task[] = [
      { id: 't-far', title: 'Tugas Jauh', subject: 'Algoritma', deadline: '2026-11-06', status: TaskStatus.TODO, priority: Priority.LOW, tags: [], subtasks: [], createdAt: 1 },
      { id: 't-urgent', title: 'Tugas Urgent Besok', subject: 'Algoritma', deadline: '2026-11-03', status: TaskStatus.TODO, priority: Priority.HIGH, tags: [], subtasks: [], createdAt: 2 }
    ];

    const plan = generatePlan({
      now: mockNow,
      courses: [],
      tasks,
      existingBlocks: [],
      settings: defaultSettings,
      daysToPlan: 1
    });

    const mondayBlocks = plan.filter(b => b.date === '2026-11-02');
    expect(mondayBlocks.length).toBeGreaterThan(0);
    // First allocated task must be the urgent task
    expect(mondayBlocks[0].taskId).toBe('t-urgent');
  });

  it('preserves manual blocks and does not duplicate or erase them', () => {
    const manualBlock: StudyBlock = {
      id: 'manual-1',
      title: 'Bimbingan Dosen Mandiri',
      date: '2026-11-02',
      startTime: '19:00',
      endTime: '20:00',
      type: 'FREE',
      completed: false,
      isAutoGenerated: false,
      updatedAt: Date.now()
    };

    const tasks: Task[] = [
      { id: 't1', title: 'Tugas Algo', subject: 'Algoritma', deadline: '2026-11-03', status: TaskStatus.TODO, priority: Priority.HIGH, tags: [], subtasks: [], createdAt: 1 }
    ];

    const plan = generatePlan({
      now: mockNow,
      courses: [],
      tasks,
      existingBlocks: [manualBlock],
      settings: defaultSettings,
      daysToPlan: 1
    });

    // Manual block must still exist
    const foundManual = plan.find(b => b.id === 'manual-1');
    expect(foundManual).toBeDefined();
    expect(foundManual?.isAutoGenerated).toBe(false);

    // Auto generated blocks must not overlap with manual block (19:00 - 20:00)
    for (const b of plan.filter(b => b.isAutoGenerated && b.date === '2026-11-02')) {
      const start = parseTimeToMinutes(b.startTime);
      const end = parseTimeToMinutes(b.endTime);
      const overlaps = start < 20 * 60 && end > 19 * 60;
      expect(overlaps).toBe(false);
    }
  });

  it('does not exceed daily study target minutes', () => {
    const tasks: Task[] = [
      { id: 't1', title: 'Tugas 1', subject: 'Algoritma', deadline: '2026-11-03', estimatedMinutes: 60, status: TaskStatus.TODO, priority: Priority.HIGH, tags: [], subtasks: [], createdAt: 1 },
      { id: 't2', title: 'Tugas 2', subject: 'Algoritma', deadline: '2026-11-03', estimatedMinutes: 60, status: TaskStatus.TODO, priority: Priority.HIGH, tags: [], subtasks: [], createdAt: 2 },
      { id: 't3', title: 'Tugas 3', subject: 'Algoritma', deadline: '2026-11-03', estimatedMinutes: 60, status: TaskStatus.TODO, priority: Priority.HIGH, tags: [], subtasks: [], createdAt: 3 },
      { id: 't4', title: 'Tugas 4', subject: 'Algoritma', deadline: '2026-11-03', estimatedMinutes: 60, status: TaskStatus.TODO, priority: Priority.HIGH, tags: [], subtasks: [], createdAt: 4 }
    ];

    const plan = generatePlan({
      now: mockNow,
      courses: [],
      tasks,
      existingBlocks: [],
      settings: { ...defaultSettings, dailyStudyTargetMinutes: 90 },
      daysToPlan: 1
    });

    const mondayBlocks = plan.filter(b => b.date === '2026-11-02');
    const totalMinutes = mondayBlocks.reduce((sum, b) => {
      return sum + (parseTimeToMinutes(b.endTime) - parseTimeToMinutes(b.startTime));
    }, 0);

    expect(totalMinutes).toBeLessThanOrEqual(90);
  });
});
