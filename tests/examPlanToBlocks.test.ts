import { describe, it, expect } from 'vitest';
import { buildExamPrepPlan, examPlanToStudyBlocks } from '../src/services/examPlanner';
import { Exam, StudyBlock } from '../src/types';

const settings = { preferredStudyHours: { start: '18:00', end: '22:00' }, breakIntervalMinutes: 10 };

const exam: Exam = {
  id: 'e1',
  courseId: 'c1',
  kind: 'UTS',
  title: 'UTS Basis Data',
  date: '2026-11-10',
  topics: [
    { id: 't1', title: 'ERD', completed: false },
    { id: 't2', title: 'Normalisasi', completed: false }
  ],
  updatedAt: 0
};

describe('examPlanToStudyBlocks', () => {
  const now = new Date(2026, 10, 5, 9, 0, 0); // 5 Nov 2026, lokal
  const plan = buildExamPrepPlan(exam, 5, now);

  it('creates user-owned EXAM_PREP blocks at the preferred start with deterministic ids', () => {
    const { blocks, skippedDates } = examPlanToStudyBlocks(exam, plan, [], settings, 1000);
    expect(skippedDates).toEqual([]);
    expect(blocks).toHaveLength(plan.length);
    expect(blocks.every(b => b.type === 'EXAM_PREP' && b.isAutoGenerated === false && b.examId === 'e1')).toBe(true);
    expect(blocks[0].startTime).toBe('18:00');
    expect(blocks[0].id).toBe(`exam-e1-${plan[0].date}`);
  });

  it('shifts a block after an existing block on the same day', () => {
    const busy: StudyBlock = {
      id: 'b1', title: 'Kerja kelompok', date: plan[0].date, startTime: '18:00', endTime: '19:00',
      type: 'FREE', completed: false, isAutoGenerated: false, updatedAt: 0
    };
    const { blocks } = examPlanToStudyBlocks(exam, plan, [busy], settings, 1000);
    expect(blocks[0].startTime).toBe('19:10');
  });

  it('skips days that cannot fit before 23:00', () => {
    const late = { preferredStudyHours: { start: '22:30', end: '23:30' }, breakIntervalMinutes: 10 };
    const { blocks, skippedDates } = examPlanToStudyBlocks(exam, plan, [], late, 1000);
    expect(blocks).toHaveLength(0);
    expect(skippedDates).toHaveLength(plan.length);
  });
});
